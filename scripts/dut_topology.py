def one_vals(topo: Dict[str, Any], profile: Dict[str, Any], family: Dict[str, Any], n: int, device_id: int = 0) -> Dict[str, str]:
    d = topo["one_dut"]["defaults"]
    p4 = fam_prefix4(topo, family, device_id)
    src_oct = int(d["source_octet_base"]) + n
    tun_oct = int(d["tunnel_octet_base"]) + n
    sink_oct = tun_oct
    sink_underlay_plen = int(d["tunnel_prefixlen"])
    return {
        "source_host_ip4": v4(p4, src_oct, int(d["source_host_suffix"]), int(d["source_net_prefixlen"])),
        "dut_source_ip4": v4(p4, src_oct, int(d["dut_source_suffix"]), int(d["source_net_prefixlen"])),
        "source_net4": v4_net(p4, src_oct, int(d["source_net_prefixlen"])),
        "traffic_sink_underlay_ip4": v4(p4, sink_oct, int(d["traffic_sink_underlay_suffix"]), sink_underlay_plen),
        "dut_sink_underlay_ip4": v4(p4, sink_oct, int(d["dut_sink_underlay_suffix"]), sink_underlay_plen),
        "traffic_sink_underlay_host4": v4_host(p4, sink_oct, int(d["traffic_sink_underlay_suffix"])),
        "dut_sink_underlay_host4": v4_host(p4, sink_oct, int(d["dut_sink_underlay_suffix"])),
        "traffic_sink_tunnel_ip4": v4(p4, tun_oct, int(d["traffic_sink_tunnel_suffix"]), int(d["tunnel_prefixlen"])),
        "dut_tunnel_ip4": v4(p4, tun_oct, int(d["dut_tunnel_suffix"]), int(d["tunnel_prefixlen"])),
        "traffic_sink_tunnel_host4": v4_host(p4, tun_oct, int(d["traffic_sink_tunnel_suffix"])),
        "dut_tunnel_host4": v4_host(p4, tun_oct, int(d["dut_tunnel_suffix"])),
        "tunnel_net4": v4_net(p4, tun_oct, int(d["tunnel_prefixlen"])),
    }


def render_one_dut_device_sections(topo: Dict[str, Any], host: str, profile_name: str, keys: Dict[str, Any], allow_placeholders=False) -> List[Dict[str, Any]]:
    p = topo["one_dut"]["profiles"][profile_name]
    d = topo["one_dut"]["defaults"]
    device_id = profile_device_id(p)
    count = int(p["count"])
    sections: List[Dict[str, Any]] = []
    source_addrs: List[str] = []
    sink_addrs: List[str] = []
    for fam in p["families"]:
        primary = fam_source_primary(topo, fam, device_id)
        if isinstance(primary, dict):
            source_addrs.append(f"{primary['address']}/{primary.get('prefixlen', d.get('source_primary_prefixlen', 24))}")
        else:
            source_addrs.append(f"{primary}/{d.get('source_primary_prefixlen', 24)}")
        for n in range(count):
            vals = one_vals(topo, p, fam, n, device_id)
            source_addrs.append(vals["dut_source_ip4"])
            sink_addrs.append(vals["dut_sink_underlay_ip4"])
    first_prefix4 = fam_prefix4(topo, p["families"][0], device_id)
    gateway = p["dut_interfaces"].get("gateway", f"{first_prefix4}.1.1")
    source_options = {"device": p["dut_interfaces"]["source_device"], "proto": "static", "gateway": gateway}
    if "dns" in p.get("dut_interfaces", {}):
        source_options["dns"] = p["dut_interfaces"]["dns"]
    elif "dns" in d:
        source_options["dns"] = d["dns"]
    sections.append(section("interface", d["dut_source_interface_name"], source_options, {"ipaddr": source_addrs}))
    sections.append(section("interface", d["dut_sink_interface_name"], {"device": p["dut_interfaces"]["sink_device"], "proto": "static"}, {"ipaddr": sink_addrs}))
    for fam in p["families"]:
        if fam_proto(topo, fam) == "plaintext":
            continue
        if_prefix = fam_if_prefix(topo, fam)
        peer_prefix = fam_peer_prefix(topo, fam)
        lpb = fam_listen_port_base(topo, fam, device_id)
        for n in range(count):
            vals = one_vals(topo, p, fam, n, device_id)
            ifname = f"{if_prefix}{n}"
            sink_if = f"{profile_name}_{ifname}"
            peer_name = f"{ifname}_peer"
            sections.append(section("interface", ifname, {
                "proto": fam_proto(topo, fam),
                "private_key": key_for(keys, host, ifname, "private_key", allow_placeholders),
                "listen_port": lpb + n,
                "mtu": fam_mtu(topo, fam),
            }, {"addresses": [vals["dut_tunnel_ip4"]]}))
            sections.append(section(f"{peer_prefix}_{ifname}", peer_name, {
                "public_key": key_for(keys, "sink", sink_if, "public_key", allow_placeholders),
                "endpoint_host": vals["traffic_sink_underlay_host4"],
                "endpoint_port": lpb + n,
                "route_allowed_ips": "1" if d.get("route_allowed_ips", True) else None,
                "persistent_keepalive": fam_keepalive(topo, fam),
            }, {"allowed_ips": allowed_from_tokens(d["dut_peer_allowed_ips"], vals)}))
    return sections


def render_one_dut_sink_sections(topo: Dict[str, Any], profile_name: str, keys: Dict[str, Any], allow_placeholders=False) -> List[Dict[str, Any]]:
    p = topo["one_dut"]["profiles"][profile_name]
    d = topo["one_dut"]["defaults"]
    device_id = profile_device_id(p)
    count = int(p["count"])
    sections: List[Dict[str, Any]] = []
    sink_if_name = d["traffic_sink_interface_name_template"].format(profile=profile_name)
    sink_addrs: List[str] = []
    for fam in p["families"]:
        for n in range(count):
            vals = one_vals(topo, p, fam, n, device_id)
            sink_addrs.append(vals["traffic_sink_underlay_ip4"])
            
    device_str = p["traffic_sink"]["device"]
    if '.' in device_str:
        ifname, vid = device_str.split('.', 1)
        sections.append(section("device", f"{profile_name}_vlan", {
            "type": "8021q",
            "ifname": ifname,
            "vid": vid,
            "name": profile_name,
            "mtu": d.get("traffic_sink_vlan_mtu", 1500)
        }))
        target_device = profile_name
    else:
        target_device = device_str
        
    sections.append(section("interface", sink_if_name, {"device": target_device, "proto": "static"}, {"ipaddr": sink_addrs}))
    for fam in p["families"]:
        if fam_proto(topo, fam) == "plaintext":
            for n in range(count):
                vals = one_vals(topo, p, fam, n, device_id)
                sections.append(section("route", f"route_{profile_name}_source{n}", {
                    "interface": sink_if_name,
                    "target": vals["source_net4"],
                    "gateway": vals["dut_sink_underlay_host4"],
                }))
            continue
        if_prefix = fam_if_prefix(topo, fam)
        peer_prefix = fam_peer_prefix(topo, fam)
        lpb = fam_listen_port_base(topo, fam, device_id)
        for n in range(count):
            vals = one_vals(topo, p, fam, n, device_id)
            dev_if = f"{if_prefix}{n}"
            local_if = d["traffic_sink_tunnel_name_template"].format(profile=profile_name, tunnel=dev_if)
            peer_name = f"{local_if}_peer"
            sections.append(section("interface", local_if, {
                "proto": fam_proto(topo, fam),
                "private_key": key_for(keys, "sink", local_if, "private_key", allow_placeholders),
                "listen_port": lpb + n,
                "mtu": fam_mtu(topo, fam),
            }, {"addresses": [vals["traffic_sink_tunnel_ip4"]]}))
            sections.append(section(f"{peer_prefix}_{local_if}", peer_name, {
                "public_key": key_for(keys, p["dut_host"], dev_if, "public_key", allow_placeholders),
                "endpoint_host": vals["dut_sink_underlay_host4"],
                "endpoint_port": lpb + n,
                "route_allowed_ips": "1",
                "persistent_keepalive": fam_keepalive(topo, fam),
            }, {"allowed_ips": allowed_from_tokens(d["traffic_sink_peer_allowed_ips"], vals)}))
            sections.append(section("route", f"route_{local_if}_source", {
                "interface": local_if,
                "target": vals["source_net4"],
                "gateway": vals["dut_tunnel_host4"],
            }))
    return sections


def render_two_dut_sink_sections(topo: Dict[str, Any]) -> List[Dict[str, Any]]:
    td = topo["two_dut"]
    device_id = int(td.get("device_id", 1))
    count = int(td["count"])
    ifcfg = td["openwrt_interfaces"]["sink"]["plaintext"]
    addrs4: List[str] = []
    addrs6: List[str] = []
    sections: List[Dict[str, Any]] = []
    for fam in td["families"]:
        for n in range(count):
            vals = two_vals(topo, fam, n, device_id)
            addrs4.append(vals["sink_plain4"])
            if fam.get("include_ipv6") and "sink_plain6" in vals:
                addrs6.append(vals["sink_plain6"])
    sections.append(section("interface", ifcfg["name"], {"device": ifcfg["device"], "proto": "static", "mtu": 1500}, {"ipaddr": addrs4, "ip6addr": addrs6}))
    for fam in td["families"]:
        for n in range(count):
            vals = two_vals(topo, fam, n, device_id)
            if fam_proto(topo, fam) == "plaintext":
                sections.extend(two_dut_plain_routes(fam, vals, n, ifcfg["name"], "source_plain_net", "dec_plain"))
                continue
            name = f"route_two_{fam_name(fam)}_{n}"
            sections.append(section("route", name, {"interface": ifcfg["name"], "target": vals["source_plain_net4"], "gateway": vals["dec_plain4"].split('/')[0]}))
    return sections


def render_openwrt_sections(topo: Dict[str, Any], host: str, keys: Dict[str, Any], allow_placeholders=False) -> List[Dict[str, Any]]:
    role = topo["hosts"][host]["role"]
    if role == "two_dut_encryptor":
        return render_two_dut_enc_sections(topo, keys, allow_placeholders)
    if role == "two_dut_decryptor":
        return render_two_dut_dec_sections(topo, keys, allow_placeholders)
    if role == "traffic_sink":
        sections = render_two_dut_sink_sections(topo)

        physical_devices = set()
        for pname, p in topo["one_dut"]["profiles"].items():
            device_str = p["traffic_sink"]["device"]
            if '.' in device_str:
                ifname, _ = device_str.split('.', 1)
                physical_devices.add(ifname)

        d = topo["one_dut"]["defaults"]
        for ifname in sorted(physical_devices):
            sections.append(section("device", ifname, {
                "name": ifname,
                "mtu": d.get("traffic_sink_parent_mtu", 9000)
            }))

        for pname in topo["one_dut"]["profiles"]:
            sections.extend(render_one_dut_sink_sections(topo, pname, keys, allow_placeholders))
        return sections
    if role == "one_dut":
        for pname, p in topo["one_dut"]["profiles"].items():
            if p["dut_host"] == host:
                return render_one_dut_device_sections(topo, host, pname, keys, allow_placeholders)
        raise ValueError(f"host {host} has role one_dut but no profile")
    raise ValueError(f"host {host} is not an OpenWrt lab host")


def render_openwrt_host(topo: Dict[str, Any], host: str, keys: Dict[str, Any], allow_placeholders=False) -> str:
    return render_uci_config(render_openwrt_sections(topo, host, keys, allow_placeholders))


def render_openwrt_host_script(topo: Dict[str, Any], host: str, keys: Dict[str, Any], allow_placeholders=False) -> str:
    return render_uci_script(render_openwrt_sections(topo, host, keys, allow_placeholders))


def render_arch_source(topo: Dict[str, Any], interface: str = "eth0") -> str:
    addresses: List[str] = []
    routes: List[Dict[str, str]] = []
    td = topo["two_dut"]
    if td.get("enabled", True):
        td_device_id = int(td.get("device_id", 1))
        for fam in td["families"]:
            p4 = fam_prefix4(topo, fam, td_device_id)
            for n in range(int(td["count"])):
                vals = two_vals(topo, fam, n, td_device_id)
                addresses.append(vals["source_plain4"])
                routes.append({"Destination": vals["sink_plain_net4"], "Gateway": vals["enc_plain4"].split('/')[0]})
                routes.append({"Destination": v4_net(p4, n, 30), "Gateway": vals["enc_plain4"].split('/')[0]})
    od = topo["one_dut"]
    if od.get("enabled", True):
        for _, p in od["profiles"].items():
            did = profile_device_id(p)
            for fam in p["families"]:
                for n in range(int(p["count"])):
                    vals = one_vals(topo, p, fam, n, did)
                    addresses.append(vals["source_host_ip4"])
                    routes.append({"Destination": vals["tunnel_net4"], "Gateway": vals["dut_source_ip4"].split('/')[0]})
    lines = ["# Generated by Ansible from topology/topology.yml", "[Match]", f"Name={interface}", "", "[Network]"]
    for a in addresses:
        lines.append(f"Address={a}")
    for r in routes:
        lines.extend(["", "[Route]", f"Destination={r['Destination']}", f"Gateway={r['Gateway']}"])
    return "\n".join(lines).rstrip() + "\n"


def all_key_targets(topo: Dict[str, Any]) -> Iterable[Tuple[str, str, str]]:
    td = topo["two_dut"]
    for fam in td["families"]:
        p = proto(topo, fam)["proto"]
        if p == "plaintext":
            continue
        if_prefix = fam_if_prefix(topo, fam)
        for n in range(int(td["count"])):
            ifname = f"{if_prefix}{n}"
            yield p, "enc", ifname
            yield p, "dec", ifname
    for profile_name, prof in topo["one_dut"]["profiles"].items():
        for fam in prof["families"]:
            p = proto(topo, fam)["proto"]
            if p == "plaintext":
                continue
            if_prefix = fam_if_prefix(topo, fam)
            for n in range(int(prof["count"])):
                ifname = f"{if_prefix}{n}"
                yield p, prof["dut_host"], ifname
                yield p, "sink", f"{profile_name}_{ifname}"


def tool_candidates_for_proto(topo: Dict[str, Any], proto_name: str) -> List[str]:
    kg = topo.get("keygen", {})
    if proto_name == "wireguard":
        override = os.environ.get("WG_KEYGEN_TOOL")
        if override:
            return [override]
        return list(kg.get("wireguard_tool_candidates", ["wg-wireguard", "wg"]))
    if proto_name == "wolfguard":
        override = os.environ.get("WOLFGUARD_KEYGEN_TOOL")
        if override:
            return [override]
        return list(kg.get("wolfguard_tool_candidates", ["wg-fips"]))
    raise ValueError(f"unsupported key proto {proto_name}")


def genkey_with_tool(tool: str) -> Tuple[str, str]:
    private_key = subprocess.check_output([tool, "genkey"], stderr=subprocess.PIPE, text=True).strip()
    public_key = subprocess.check_output([tool, "pubkey"], input=private_key + "\n", stderr=subprocess.PIPE, text=True).strip()
    return private_key, public_key


def genkey_with_candidates(candidates: List[str]) -> Tuple[str, str, str, List[str]]:
    errors: List[str] = []
    for tool in candidates:
        if not shutil.which(tool):
            errors.append(f"{tool}: not found")
            continue
        try:
            priv, pub = genkey_with_tool(tool)
            return priv, pub, tool, errors
        except subprocess.CalledProcessError as e:
            stderr = (e.stderr or "").strip()
            errors.append(f"{tool}: rc={e.returncode}" + (f" stderr={stderr}" if stderr else ""))
    raise RuntimeError("all keygen tools failed: " + "; ".join(errors))


def generate_keys(topo: Dict[str, Any], out_path: Path, force: bool = False, skip_wolfguard: bool = False, allow_dummy: bool = False) -> Dict[str, Any]:
    existing = load_yaml(out_path) if out_path.exists() and not force else {}
    keys = existing.get("generated_tunnel_keys", {})
    meta = existing.get("generated_tunnel_key_meta", {})
    for proto_name, host, ifname in all_key_targets(topo):
        if proto_name == "wolfguard" and skip_wolfguard:
            continue
        keys.setdefault(host, {})
        if ifname in keys[host] and keys[host][ifname].get("private_key") and keys[host][ifname].get("public_key"):
            continue
        candidates = tool_candidates_for_proto(topo, proto_name)
        if allow_dummy:
            raw = f"{host}:{ifname}:{proto_name}".encode()
            priv = base64.b64encode(raw).decode().ljust(44, "=")[:44]
            pub = base64.b64encode(b"pub:" + raw).decode().ljust(44, "=")[:44]
            used_tool = "dummy"
        else:
            try:
                priv, pub, used_tool, _ = genkey_with_candidates(candidates)
            except Exception as e:
                raise SystemExit(f"Could not generate {proto_name} key for {host}.{ifname}: {e}")
        keys[host][ifname] = {"private_key": priv, "public_key": pub, "proto": proto_name}
        meta.setdefault(host, {})[ifname] = {"tool": used_tool}
    data = {"generated_tunnel_keys": keys, "generated_tunnel_key_meta": meta}
    dump_yaml(out_path, data)
    return data
