def load_yaml(path: str | Path) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def dump_yaml(path: str | Path, data: Dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        yaml.safe_dump(data, f, sort_keys=False)


def section(section_type: str, name: str, options: Optional[Dict[str, Any]] = None,
            lists: Optional[Dict[str, List[Any]]] = None) -> Dict[str, Any]:
    return {
        "type": section_type,
        "name": name,
        "options": {k: v for k, v in (options or {}).items() if v is not None},
        "lists": {k: list(v) for k, v in (lists or {}).items() if v},
    }


def render_uci_config(sections: List[Dict[str, Any]]) -> str:
    out = [
        "# Generated by Ansible from topology/topology.yml",
        "# This is a lab-owned fragment preview, not the complete OpenWrt network file.",
        "",
    ]
    for sec in sections:
        out.append(f"config {sec['type']} '{sec['name']}'")
        for k, v in sec.get("options", {}).items():
            out.append(f"\toption {k} '{v}'")
        for k, values in sec.get("lists", {}).items():
            for v in values:
                out.append(f"\tlist {k} '{v}'")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def shquote(value: Any) -> str:
    s = str(value)
    return "'" + s.replace("'", "'\\''") + "'"


def render_uci_script(sections: List[Dict[str, Any]]) -> str:
    named = sorted({s["name"] for s in sections})
    peer_types = sorted({s["type"] for s in sections if s["type"].startswith(("wireguard_", "wolfguard_"))})
    out = [
        "#!/bin/sh",
        "set -eu",
        "",
        "# Generated by Ansible from topology/topology.yml",
        "# Applies only lab-owned network sections and leaves unrelated config intact.",
        "",
        "delete_all_sections_of_type() {",
        "    type=\"$1\"",
        "    while uci -q delete network.@${type}[0]; do :; done",
        "}",
        "",
    ]
    
    out += [
        "# Clean up all named peer sections dynamically",
        "for peer in $(uci -q show network | awk -F'[.=]' '/=(wireguard|wolfguard)_(wg|wolf|[a-zA-Z0-9_]+_(wg|wolf))[0-9]+$/ {print $2}' | sort -u); do",
        "    uci -q delete network.\"$peer\"",
        "done",
        "",
        "# Clean up old generated interfaces",
        "for iface in $(uci -q show network | awk -F'[.=]' '/=interface$/ {print $2}'); do",
        "    case \"$iface\" in",
        "        wg[0-9]*|wolf[0-9]*|plaintext[0-9]*) uci -q delete network.\"$iface\" ;;",
        "        *_wg[0-9]*|*_wolf[0-9]*|*_plaintext[0-9]*) uci -q delete network.\"$iface\" ;;",
        "    esac",
        "done",
        "",
        "# Clean up old generated device sections",
        "for dev in $(uci -q show network | awk -F'[.=]' '/=device$/ {print $2}'); do",
        "    case \"$dev\" in",
        "        *_vlan) uci -q delete network.\"$dev\" ;;",
        "    esac",
        "done",
        "",
        "# Clean up old named routes",
        "for route in $(uci -q show network | awk -F'[.=]' '/=(route|route6)$/ {print $2}'); do",
        "    case \"$route\" in",
        "        route_two_*|route_*_source|route_d[0-9]*_source[0-9]*) uci -q delete network.\"$route\" ;;",
        "    esac",
        "done",
        "",
        "# Clean up anonymous route and route6 sections pointing to lab interfaces",
        "while true; do",
        "    to_delete=$(uci -q show network | grep -E \"^network\\.@route[6]?\\[[0-9]+\\]\\.interface='?(sink|source|(d[0-9]+_)?(wg|wolf|plaintext)[0-9]*)'?\" | cut -d. -f2 | head -n1)",
        "    if [ -n \"$to_delete\" ]; then",
        "        uci -q delete network.\"$to_delete\"",
        "    else",
        "        break",
        "    fi",
        "done",
        "",
    ]
    
    for name in named:
        out.append(f"uci -q delete network.{name} || true")
    out += ["", "uci -q batch <<'UCI'"]
    for sec in sections:
        name = sec["name"]
        out.append(f"set network.{name}={sec['type']}")
        for k, v in sec.get("options", {}).items():
            out.append(f"set network.{name}.{k}={shquote(v)}")
        for k, values in sec.get("lists", {}).items():
            for v in values:
                out.append(f"add_list network.{name}.{k}={shquote(v)}")
    out += ["commit network", "UCI", ""]
    out += ["/etc/init.d/network reload || /etc/init.d/network restart"]
    return "\n".join(out).rstrip() + "\n"


def proto(topo: Dict[str, Any], family: Dict[str, Any]) -> Dict[str, Any]:
    return topo["protocols"][family["protocol"]]


def fam_if_prefix(topo: Dict[str, Any], family: Dict[str, Any]) -> str:
    return family.get("interface_prefix") or proto(topo, family)["interface_prefix"]


def fam_peer_prefix(topo: Dict[str, Any], family: Dict[str, Any]) -> str:
    return family.get("peer_section_prefix") or proto(topo, family)["peer_section_prefix"]


def fam_proto(topo: Dict[str, Any], family: Dict[str, Any]) -> str:
    return proto(topo, family)["proto"]


def fam_keepalive(topo: Dict[str, Any], family: Dict[str, Any]) -> Optional[int]:
    return family.get("persistent_keepalive", proto(topo, family).get("persistent_keepalive"))


def fam_mtu(topo: Dict[str, Any], family: Dict[str, Any]) -> Optional[int]:
    return family.get("mtu", proto(topo, family).get("default_mtu"))


def fam_name(family: Dict[str, Any]) -> str:
    return family.get("name", family["protocol"])


def fam_prefix4(topo: Dict[str, Any], family: Dict[str, Any], device_id: int) -> str:
    if "prefix4" in family:
        return family["prefix4"]
    sb = proto(topo, family).get("subnet_base")
    if sb is not None:
        return f"10.{int(sb) + device_id}"
    raise ValueError(f"Cannot compute prefix4 for family {fam_name(family)}: no subnet_base in protocol")


def fam_prefix6(topo: Dict[str, Any], family: Dict[str, Any], device_id: int) -> Optional[str]:
    if "prefix6" in family:
        return family["prefix6"]
    sb = proto(topo, family).get("subnet_base")
    if sb is not None:
        return f"10:{int(sb) + device_id}"
    return None


def fam_listen_port_base(topo: Dict[str, Any], family: Dict[str, Any], device_id: int) -> Optional[int]:
    if "listen_port_base" in family:
        return int(family["listen_port_base"])
    base = proto(topo, family).get("listen_port_base")
    if base is not None:
        return int(base) + device_id * 100
    return None


def fam_source_primary(topo: Dict[str, Any], family: Dict[str, Any], device_id: int) -> Any:
    if "source_primary" in family:
        return family["source_primary"]
    p4 = fam_prefix4(topo, family, device_id)
    return f"{p4}.1.2"


def profile_device_id(profile: Dict[str, Any]) -> int:
    if "device_id" in profile:
        return int(profile["device_id"])
    host = profile.get("dut_host", "")
    num = ''.join(c for c in host if c.isdigit())
    if num:
        return int(num)
    raise ValueError(f"Cannot determine device_id for profile: no device_id field and cannot parse dut_host '{host}'")


def v4(prefix: str, third: int, host: int, plen: int) -> str:
    return f"{prefix}.{third}.{host}/{plen}"


def v4_host(prefix: str, third: int, host: int) -> str:
    return f"{prefix}.{third}.{host}"


def v4_net(prefix: str, third: int, plen: int = 30) -> str:
    return f"{prefix}.{third}.0/{plen}"


def v6(prefix: str, third: int, host: int, plen: int = 126) -> str:
    return f"{prefix}:{third}::{host}/{plen}"


def v6_host(prefix: str, third: int, host: int) -> str:
    return f"{prefix}:{third}::{host}"


def v6_net(prefix: str, third: int, plen: int = 126) -> str:
    return f"{prefix}:{third}::/{plen}"


def key_for(keys: Dict[str, Any], host: str, iface: str, field: str, allow_placeholders=False) -> str:
    try:
        return keys["generated_tunnel_keys"][host][iface][field]
    except Exception:
        if allow_placeholders:
            return f"CHANGE_ME_{host}_{iface}_{field}"
        raise KeyError(f"missing key {field} for {host}.{iface}; run playbooks/generate_keys.yml")


def two_vals(topo: Dict[str, Any], family: Dict[str, Any], n: int, device_id: int = 1) -> Dict[str, str]:
    f = topo["two_dut"]["formulas"]
    p4 = fam_prefix4(topo, family, device_id)
    p6 = fam_prefix6(topo, family, device_id)
    src_oct = int(f["source_octet_base"]) + n
    tun_oct = int(f["tunnel_octet_base"]) + n
    sink_oct = int(f["sink_octet_base"]) + n
    underlay_oct = int(f["underlay_octet"])
    v = {
        "enc_underlay4": v4(p4, underlay_oct, int(f["enc_tunnel_suffix"]), int(f["ipv4_prefixlen"])),
        "dec_underlay4": v4(p4, underlay_oct, int(f["dec_tunnel_suffix"]), int(f["ipv4_prefixlen"])),
        "enc_underlay_host4": v4_host(p4, underlay_oct, int(f["enc_tunnel_suffix"])),
        "dec_underlay_host4": v4_host(p4, underlay_oct, int(f["dec_tunnel_suffix"])),
        "source_plain4": v4(p4, src_oct, int(f["source_host_suffix"]), int(f["ipv4_prefixlen"])),
        "enc_plain4": v4(p4, src_oct, int(f["enc_plain_suffix"]), int(f["ipv4_prefixlen"])),
        "enc_tunnel4": v4(p4, tun_oct, int(f["enc_tunnel_suffix"]), int(f["ipv4_prefixlen"])),
        "dec_tunnel4": v4(p4, tun_oct, int(f["dec_tunnel_suffix"]), int(f["ipv4_prefixlen"])),
        "sink_plain4": v4(p4, sink_oct, int(f["sink_host_suffix"]), int(f["ipv4_prefixlen"])),
        "dec_plain4": v4(p4, sink_oct, int(f["dec_plain_suffix"]), int(f["ipv4_prefixlen"])),
        "source_plain_net4": v4_net(p4, src_oct, int(f["ipv4_prefixlen"])),
        "sink_plain_net4": v4_net(p4, sink_oct, int(f["ipv4_prefixlen"])),
        "enc_tunnel_host4": v4_host(p4, tun_oct, int(f["enc_tunnel_suffix"])),
        "dec_tunnel_host4": v4_host(p4, tun_oct, int(f["dec_tunnel_suffix"])),
    }
    if p6:
        plen6 = int(f["ipv6_prefixlen"])
        v.update({
            "enc_underlay6": v6(p6, underlay_oct, int(f["enc_tunnel_suffix"]), plen6),
            "dec_underlay6": v6(p6, underlay_oct, int(f["dec_tunnel_suffix"]), plen6),
            "source_plain6": v6(p6, src_oct, int(f["source_host_suffix"]), plen6),
            "enc_plain6": v6(p6, src_oct, int(f["enc_plain_suffix"]), plen6),
            "enc_tunnel6": v6(p6, tun_oct, int(f["enc_tunnel_suffix"]), plen6),
            "dec_tunnel6": v6(p6, tun_oct, int(f["dec_tunnel_suffix"]), plen6),
            "sink_plain6": v6(p6, sink_oct, int(f["sink_host_suffix"]), plen6),
            "dec_plain6": v6(p6, sink_oct, int(f["dec_plain_suffix"]), plen6),
            "source_plain_net6": v6_net(p6, src_oct, plen6),
            "sink_plain_net6": v6_net(p6, sink_oct, plen6),
            "enc_tunnel_host6": v6_host(p6, tun_oct, int(f["enc_tunnel_suffix"])),
            "dec_tunnel_host6": v6_host(p6, tun_oct, int(f["dec_tunnel_suffix"])),
        })
    return v


def allowed_from_tokens(tokens: List[str], values: Dict[str, str]) -> List[str]:
    return [values[t] for t in tokens if t in values]


def two_dut_plain_routes(family: Dict[str, Any], values: Dict[str, str], n: int,
                         interface: str, target: str, gateway: str) -> List[Dict[str, Any]]:
    name = f"route_two_{fam_name(family)}_{n}"
    sections = [section("route", name, {
        "interface": interface,
        "target": values[f"{target}4"],
        "gateway": values[f"{gateway}4"].split('/')[0],
    })]
    if family.get("include_ipv6") and f"{target}6" in values:
        sections.append(section("route6", f"{name}_6", {
            "interface": interface,
            "target": values[f"{target}6"],
            "gateway": values[f"{gateway}6"].split('/')[0],
        }))
    return sections


def render_two_dut_enc_sections(topo: Dict[str, Any], keys: Dict[str, Any], allow_placeholders=False) -> List[Dict[str, Any]]:
    td = topo["two_dut"]
    device_id = int(td.get("device_id", 1))
    count = int(td["count"])
    ifcfg = td["openwrt_interfaces"]["enc"]
    underlay4: List[str] = []
    underlay6: List[str] = []
    plain4: List[str] = []
    plain6: List[str] = []
    sections: List[Dict[str, Any]] = []
    for fam in td["families"]:
        for n in range(count):
            vals = two_vals(topo, fam, n, device_id)
            if fam_proto(topo, fam) == "plaintext":
                underlay4.append(vals["enc_tunnel4"])
                if fam.get("include_ipv6") and "enc_tunnel6" in vals:
                    underlay6.append(vals["enc_tunnel6"])
            elif n == 0:
                underlay4.append(vals["enc_underlay4"])
                if fam.get("include_ipv6") and "enc_underlay6" in vals:
                    underlay6.append(vals["enc_underlay6"])
            plain4.append(vals["enc_plain4"])
            if fam.get("include_ipv6") and "enc_plain6" in vals:
                plain6.append(vals["enc_plain6"])
    gateway = f"{fam_prefix4(topo, td['families'][0], device_id)}.1.1"
    source_options = {"device": ifcfg["plaintext"]["device"], "proto": "static", "mtu": 1500, "gateway": gateway}
    if "dns" in td:
        source_options["dns"] = td["dns"]
    sections.append(section("interface", ifcfg["underlay"]["name"], {"device": ifcfg["underlay"]["device"], "proto": "static", "mtu": 1500}, {"ipaddr": underlay4, "ip6addr": underlay6}))
    sections.append(section("interface", ifcfg["plaintext"]["name"], source_options, {"ipaddr": plain4, "ip6addr": plain6}))
    for fam in td["families"]:
        if fam_proto(topo, fam) == "plaintext":
            for n in range(count):
                vals = two_vals(topo, fam, n, device_id)
                sections.extend(two_dut_plain_routes(fam, vals, n, ifcfg["underlay"]["name"], "sink_plain_net", "dec_tunnel"))
            continue
        if_prefix = fam_if_prefix(topo, fam)
        peer_prefix = fam_peer_prefix(topo, fam)
        lpb = fam_listen_port_base(topo, fam, device_id)
        for n in range(count):
            vals = two_vals(topo, fam, n, device_id)
            ifname = f"{if_prefix}{n}"
            peer_name = f"{ifname}_peer"
            addrs = [vals["enc_tunnel4"]]
            if fam.get("include_ipv6") and "enc_tunnel6" in vals:
                addrs.append(vals["enc_tunnel6"])
            sections.append(section("interface", ifname, {
                "proto": fam_proto(topo, fam),
                "private_key": key_for(keys, "enc", ifname, "private_key", allow_placeholders),
                "listen_port": lpb + n,
                "mtu": fam_mtu(topo, fam),
            }, {"addresses": addrs}))
            sections.append(section(f"{peer_prefix}_{ifname}", peer_name, {
                "public_key": key_for(keys, "dec", ifname, "public_key", allow_placeholders),
                "endpoint_host": vals["dec_underlay_host4"],
                "endpoint_port": lpb + n,
                "route_allowed_ips": "1",
                "persistent_keepalive": fam_keepalive(topo, fam),
            }, {"allowed_ips": allowed_from_tokens(fam["allowed_ips"]["enc_peer"], vals)}))
    return sections


